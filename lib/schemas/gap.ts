import { z } from "zod";

import { skillImportanceSchema } from "./career";
import { idSchema, percentageSchema, proficiencySchema } from "./common";
import { skillCategorySchema } from "./skill";

export const gapPrioritySchema = z.enum(["critical", "important", "optional"]);

/** One missing or under-developed skill for a target career. */
export const skillGapEntrySchema = z.object({
  skillId: idSchema,
  name: z.string().min(2).max(60),
  category: skillCategorySchema,
  importance: skillImportanceSchema,
  requiredLevel: proficiencySchema,
  currentLevel: proficiencySchema,
  /** requiredLevel - currentLevel, always >= 1 for a gap. */
  gap: proficiencySchema,
  priority: gapPrioritySchema,
  /** Career phase ids that teach this skill. */
  coveredInPhaseIds: z.array(idSchema),
});

/** A skill the student already meets or exceeds. */
export const skillStrengthSchema = z.object({
  skillId: idSchema,
  name: z.string().min(2).max(60),
  level: proficiencySchema,
});

/**
 * Result of comparing a student's skills with a career's requirements.
 * Computed locally, never generated by the AI.
 */
export const skillGapAnalysisSchema = z.object({
  careerId: idSchema,
  targetCareerTitle: z.string().min(3).max(80),
  /** Weighted coverage of the career's skills, 0–100. */
  readinessPercent: percentageSchema,
  totalRequiredSkills: z.number().int().min(0),
  metSkills: z.number().int().min(0),
  gaps: z.array(skillGapEntrySchema),
  strengths: z.array(skillStrengthSchema),
});
